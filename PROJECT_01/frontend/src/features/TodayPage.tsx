import { useState, type FormEvent } from 'react';
import { Link } from 'react-router-dom';
import { errorMessage } from '../api/client';
import {
  useDashboard,
  useEmailMutations,
  useGenerateBriefing,
  useMeta,
  usePriorityMutations,
  useReminderMutations,
  useTaskMutations,
  useTz,
} from '../api/hooks';
import type { CalendarEvent, Dashboard, Task } from '../api/types';
import { EventForm } from '../components/EventForm';
import { useFeedback } from '../components/feedback';
import { TaskForm } from '../components/TaskForm';
import { TaskRow } from '../components/TaskRow';
import { Empty, ErrorNotice, Section, Skeleton, Spinner } from '../components/ui';
import { daysBetween, fmtLongDate, fmtTime, greeting, relativeFromNow, wallTime, zonedToUtc } from '../lib/dates';

export function TodayPage() {
  const { data, isLoading, error, refetch } = useDashboard();
  if (isLoading) return <Skeleton lines={6} />;
  if (error || !data) return <ErrorNotice error={error} retry={() => refetch()} />;
  return <TodayView d={data} />;
}

function TodayView({ d }: { d: Dashboard }) {
  const tz = useTz();
  const dayOfYear = daysBetween(`${d.date.slice(0, 4)}-01-01`, d.date) + 1;
  const c = d.counts;

  return (
    <>
      <header className="masthead">
        <div>
          <div className="kicker">{greeting(tz)}, {d.user_name}</div>
          <h1 className="masthead-date">{fmtLongDate(d.date)}</h1>
          <div className="masthead-meta">
            Vol. {d.date.slice(0, 4)} · No. {dayOfYear} · {d.timezone.replace('_', ' ')}
          </div>
        </div>
      </header>

      <nav className="ticker" aria-label="Today at a glance">
        <Link className="ticker-item" to="/calendar">
          <strong>{c.events_today}</strong> {c.events_today === 1 ? 'event' : 'events'}
        </Link>
        <Link className="ticker-item" to="/tasks">
          <strong>{c.due_today}</strong> due today
        </Link>
        <Link className={`ticker-item ${c.overdue ? 'alert' : ''}`} to="/tasks?view=overdue">
          <strong>{c.overdue}</strong> overdue
        </Link>
        <span className="ticker-item">
          <strong>{c.done_today}</strong> done today
        </span>
        <Link className="ticker-item" to="/inbox">
          <strong>{d.email_connected ? c.unread_emails : '—'}</strong> unread
        </Link>
      </nav>

      <div className="paper-grid">
        <div className="col first span-8">
          <BriefingCard d={d} />
        </div>
        <div className="col span-4">
          <PrioritiesCard d={d} />
        </div>
        <div className="col first span-4">
          <AgendaCard d={d} />
        </div>
        <div className="col span-4">
          <DueCard d={d} />
        </div>
        <div className="col span-4">
          <RemindersCard d={d} />
          <div style={{ height: 26 }} />
          <InboxCard d={d} />
        </div>
      </div>
    </>
  );
}

// --- Briefing (lead story) -------------------------------------------------------------

function BriefingCard({ d }: { d: Dashboard }) {
  const tz = useTz();
  const { data: meta } = useMeta();
  const generate = useGenerateBriefing();
  const { toast } = useFeedback();
  const b = d.briefing;

  async function run() {
    try {
      const result = await generate.mutateAsync();
      if (result.note) toast({ title: 'Briefing ready (rule-based)', body: result.note, tone: 'error' });
    } catch (err) {
      toast({ title: 'Could not generate the briefing', body: errorMessage(err), tone: 'error' });
    }
  }

  const button = (
    <button className="btn btn-sm" onClick={run} disabled={generate.isPending}>
      {generate.isPending ? <Spinner label="Writing briefing" /> : null}
      {generate.isPending ? 'Writing…' : b ? 'Regenerate' : 'Generate briefing'}
    </button>
  );

  return (
    <Section title="The briefing" action={b ? button : undefined}>
      {!b ? (
        <Empty
          title="No briefing yet today"
          action={button}
        >
          {meta?.ai_enabled
            ? `Claude (${meta.ai_model}) will summarise your schedule, tasks, reminders and inbox.`
            : 'A rule-based summary of your day. Add an ANTHROPIC_API_KEY to have Claude write it instead.'}
        </Empty>
      ) : (
        <article>
          <h2 className="briefing-headline">{b.content.headline}</h2>
          <div className="byline">
            {b.source === 'ai' ? (
              <span className="source-badge ai" title="Generated by the Claude API">
                ✦ Written by Claude · {b.model}
              </span>
            ) : (
              <span className="source-badge rule" title="Deterministic summary, no AI involved">
                Rule-based summary
              </span>
            )}
            <span className="mono">{fmtTime(b.created_at, tz)}</span>
          </div>
          {b.note && <div className="notice">{b.note}</div>}
          <p className="briefing-summary">{b.content.summary}</p>
          <div className="briefing-cols">
            <div>
              <h3>Suggested focus</h3>
              {b.content.focus.length ? (
                <ol className="plain-list">
                  {b.content.focus.map((f, i) => (
                    <li key={i} className="focus-item">
                      <span className="focus-num">{i + 1}</span>
                      <span>
                        <strong>{f.title}</strong>
                        <br />
                        <span className="muted" style={{ fontSize: '0.82rem' }}>
                          {f.reason}
                        </span>
                      </span>
                    </li>
                  ))}
                </ol>
              ) : (
                <p className="muted">Nothing urgent. A good day to plan ahead.</p>
              )}
            </div>
            <div>
              <h3>Schedule notes</h3>
              <ul className="plain-list">
                {[...b.content.schedule_notes, ...b.content.heads_up].map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
                {!b.content.schedule_notes.length && !b.content.heads_up.length && <li className="muted">Nothing to flag.</li>}
              </ul>
            </div>
          </div>
        </article>
      )}
    </Section>
  );
}

// --- Priorities ------------------------------------------------------------------------

function PrioritiesCard({ d }: { d: Dashboard }) {
  const { set, toggle } = usePriorityMutations();
  const { toast } = useFeedback();
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState<{ text: string; task_id: number | null }[]>([]);

  const startEdit = (seed?: { text: string; task_id: number | null }[]) => {
    const base = seed ?? d.priorities.map((p) => ({ text: p.text, task_id: p.task_id }));
    setDraft([...base, { text: '', task_id: null }, { text: '', task_id: null }, { text: '', task_id: null }].slice(0, 3));
    setEditing(true);
  };

  async function save(e: FormEvent) {
    e.preventDefault();
    const items = draft
      .filter((x) => x.text.trim())
      .map((x) => ({ text: x.text.trim(), task_id: x.task_id, done: d.priorities.find((p) => p.text === x.text.trim())?.done ?? false }));
    try {
      await set.mutateAsync({ day: d.date, items });
      setEditing(false);
      toast({ title: 'Priorities set' });
    } catch (err) {
      toast({ title: 'Could not save priorities', body: errorMessage(err), tone: 'error' });
    }
  }

  const suggestions = d.briefing?.content.focus ?? [];

  if (editing) {
    return (
      <Section title="Today’s three">
        <form onSubmit={save}>
          {draft.map((item, i) => (
            <div className="priority" key={i}>
              <span className="priority-num" aria-hidden>
                {i + 1}
              </span>
              <input
                className="input"
                aria-label={`Priority ${i + 1}`}
                value={item.text}
                maxLength={200}
                autoFocus={i === 0}
                onChange={(e) => setDraft(draft.map((x, j) => (j === i ? { text: e.target.value, task_id: null } : x)))}
              />
              <span />
            </div>
          ))}
          <div className="form-actions">
            <button type="button" className="btn btn-ghost btn-sm" onClick={() => setEditing(false)}>
              Cancel
            </button>
            <button type="submit" className="btn btn-primary btn-sm" disabled={set.isPending}>
              Save
            </button>
          </div>
        </form>
      </Section>
    );
  }

  return (
    <Section
      title="Today’s three"
      action={
        <button className="btn btn-ghost btn-sm" onClick={() => startEdit()}>
          {d.priorities.length ? 'Edit' : 'Set'}
        </button>
      }
    >
      {[0, 1, 2].map((i) => {
        const p = d.priorities[i];
        return (
          <div key={i} className={`priority ${p ? 'filled' : ''} ${p?.done ? 'done' : ''}`}>
            <span className="priority-num" aria-hidden>
              {i + 1}
            </span>
            {p ? (
              <>
                <span className="priority-text">{p.text}</span>
                <input
                  type="checkbox"
                  className="check"
                  checked={p.done}
                  aria-label={`Mark priority “${p.text}” ${p.done ? 'not done' : 'done'}`}
                  onChange={() => toggle.mutate({ id: p.id, done: !p.done })}
                />
              </>
            ) : (
              <button className="btn btn-ghost btn-sm" style={{ justifySelf: 'start' }} onClick={() => startEdit()}>
                Add a priority…
              </button>
            )}
          </div>
        );
      })}
      {!d.priorities.length && suggestions.length > 0 && (
        <button
          className="btn btn-sm"
          style={{ marginTop: 12 }}
          onClick={() => startEdit(suggestions.map((f) => ({ text: f.title, task_id: f.task_id })))}
        >
          Use the briefing’s suggestions
        </button>
      )}
    </Section>
  );
}

// --- Agenda ----------------------------------------------------------------------------

function AgendaCard({ d }: { d: Dashboard }) {
  const tz = useTz();
  const [open, setOpen] = useState<CalendarEvent | null | 'new'>(null);
  const now = Date.now();
  const allDay = d.events.filter((e) => e.all_day);
  const timed = d.events.filter((e) => !e.all_day);
  const nowIndex = timed.findIndex((e) => new Date(e.start_at).getTime() > now);
  const nextHour = `${String(Math.min(wallTime(new Date(), tz).hour + 1, 23)).padStart(2, '0')}:00`;

  const item = (e: CalendarEvent) => (
    <button
      key={e.id}
      className={`agenda-item ${!e.all_day && new Date(e.end_at).getTime() < now ? 'past' : ''}`}
      style={{ background: 'none', border: 0, borderBottom: '1px dotted var(--rule)', width: '100%', textAlign: 'left', cursor: 'pointer', color: 'inherit' }}
      onClick={() => setOpen(e)}
    >
      <span className="agenda-time">{e.all_day ? 'All day' : fmtTime(e.start_at, tz)}</span>
      <span className="agenda-bar" style={{ background: e.color }} aria-hidden />
      <span>
        <span className="agenda-title">{e.title}</span>
        <span className="agenda-sub" style={{ display: 'block' }}>
          {e.all_day ? '' : `until ${fmtTime(e.end_at, tz)}`}
          {e.location ? ` · ${e.location}` : ''}
          {e.source_name ? ` · ${e.source_name}` : ''}
        </span>
      </span>
    </button>
  );

  return (
    <Section
      title="Schedule"
      count={d.events.length || undefined}
      action={
        <button className="btn btn-ghost btn-sm" onClick={() => setOpen('new')}>
          Add
        </button>
      }
    >
      {d.events.length === 0 ? (
        <Empty title="Nothing on the calendar">
          {d.calendars_connected === 0 ? (
            <>
              Connect Google, Outlook or Apple Calendar in <Link to="/settings">Settings</Link>, or add an event.
            </>
          ) : (
            'A free day. Protect it.'
          )}
        </Empty>
      ) : (
        <div>
          {allDay.map(item)}
          {timed.map((e, i) => (
            <div key={e.id}>
              {i === nowIndex && <div className="now-line">Now · {fmtTime(new Date().toISOString(), tz)}</div>}
              {item(e)}
            </div>
          ))}
          {nowIndex === -1 && timed.length > 0 && <div className="now-line">Now · {fmtTime(new Date().toISOString(), tz)}</div>}
        </div>
      )}
      <EventForm
        open={open !== null}
        onClose={() => setOpen(null)}
        event={open === 'new' ? null : open}
        slot={open === 'new' ? { date: d.date, time: nextHour } : null}
      />
    </Section>
  );
}

// --- Due tasks -------------------------------------------------------------------------

function DueCard({ d }: { d: Dashboard }) {
  const { create } = useTaskMutations();
  const { toast } = useFeedback();
  const [title, setTitle] = useState('');
  const [editing, setEditing] = useState<Task | null>(null);

  async function add(e: FormEvent) {
    e.preventDefault();
    if (!title.trim()) return;
    try {
      await create.mutateAsync({ title: title.trim(), due_date: d.date });
      setTitle('');
    } catch (err) {
      toast({ title: 'Could not add task', body: errorMessage(err), tone: 'error' });
    }
  }

  return (
    <Section title="Due" count={d.tasks.length || undefined} action={<Link to="/tasks" className="btn btn-ghost btn-sm">All tasks</Link>}>
      {d.tasks.length === 0 ? (
        <Empty title="Nothing due">You’re clear for today. {d.counts.upcoming > 0 && `${d.counts.upcoming} upcoming.`}</Empty>
      ) : (
        d.tasks.map((t) => <TaskRow key={t.id} task={t} today={d.date} onEdit={setEditing} />)
      )}
      <form className="inline-add" onSubmit={add}>
        <input
          className="input"
          placeholder="Add a task for today…"
          aria-label="New task for today"
          value={title}
          maxLength={200}
          onChange={(e) => setTitle(e.target.value)}
        />
        <button className="btn btn-sm" disabled={!title.trim() || create.isPending}>
          Add
        </button>
      </form>
      <TaskForm open={editing !== null} task={editing} onClose={() => setEditing(null)} />
    </Section>
  );
}

// --- Reminders -------------------------------------------------------------------------

function RemindersCard({ d }: { d: Dashboard }) {
  const tz = useTz();
  const { create, snooze, dismiss } = useReminderMutations();
  const { toast } = useFeedback();
  const [text, setText] = useState('');
  const [time, setTime] = useState(() => `${String(Math.min(wallTime(new Date(), tz).hour + 1, 23)).padStart(2, '0')}:00`);

  async function add(e: FormEvent) {
    e.preventDefault();
    if (!text.trim()) return;
    try {
      await create.mutateAsync({ text: text.trim(), remind_at: zonedToUtc(d.date, time, tz).toISOString() });
      setText('');
      toast({ title: 'Reminder set', body: `${time} · ${text.trim()}` });
    } catch (err) {
      toast({ title: 'Could not set reminder', body: errorMessage(err), tone: 'error' });
    }
  }

  return (
    <Section title="Reminders" count={d.reminders.length || undefined}>
      {d.reminders.length === 0 && <p className="muted" style={{ fontSize: '0.86rem', margin: '4px 0' }}>No reminders left today.</p>}
      {d.reminders.map((r) => {
        const due = new Date(r.remind_at).getTime() <= Date.now();
        return (
          <div className="row" key={r.id}>
            <span className="mono" style={{ fontSize: '0.8rem', color: due ? 'var(--accent)' : undefined }}>
              {fmtTime(r.remind_at, tz)}
            </span>
            <div className="row-main">
              <div className="row-title">{r.text}</div>
              <div className="row-sub">{relativeFromNow(r.remind_at)}</div>
            </div>
            <div className="row-actions" style={{ opacity: 1 }}>
              {due && (
                <button className="btn btn-ghost btn-sm" onClick={() => snooze.mutate({ id: r.id, minutes: 10 })}>
                  +10m
                </button>
              )}
              <button className="btn btn-ghost btn-sm" onClick={() => dismiss.mutate(r.id)} aria-label={`Dismiss reminder “${r.text}”`}>
                Done
              </button>
            </div>
          </div>
        );
      })}
      <form className="inline-add" onSubmit={add}>
        <input className="input" type="time" aria-label="Reminder time" value={time} onChange={(e) => setTime(e.target.value)} style={{ width: 110 }} />
        <input className="input" placeholder="Remind me to…" aria-label="Reminder text" value={text} maxLength={200} onChange={(e) => setText(e.target.value)} />
        <button className="btn btn-sm" disabled={!text.trim() || create.isPending}>
          Set
        </button>
      </form>
    </Section>
  );
}

// --- Inbox -----------------------------------------------------------------------------

function InboxCard({ d }: { d: Dashboard }) {
  const tz = useTz();
  const { sync, makeTask } = useEmailMutations();
  const { toast } = useFeedback();

  async function doSync() {
    try {
      const r = await sync.mutateAsync();
      toast({ title: 'Inbox synced', body: `${r.fetched} messages checked, ${r.attention} need attention` });
    } catch (err) {
      toast({ title: 'Email sync failed', body: errorMessage(err), tone: 'error' });
    }
  }

  return (
    <Section
      title="Inbox"
      count={d.email_connected ? d.counts.attention_emails : undefined}
      action={
        d.email_connected && (
          <button className="btn btn-ghost btn-sm" onClick={doSync} disabled={sync.isPending}>
            {sync.isPending ? 'Syncing…' : 'Sync'}
          </button>
        )
      }
    >
      {!d.email_connected ? (
        <Empty title="No mailbox connected" action={<Link to="/settings" className="btn btn-sm">Connect email</Link>}>
          Read-only IMAP: Gmail, Outlook, Fastmail and others.
        </Empty>
      ) : d.emails.length === 0 ? (
        <p className="muted" style={{ fontSize: '0.86rem' }}>Inbox zero. Nothing unread or flagged.</p>
      ) : (
        <>
          {d.emails.map((m) => (
            <div className="row" key={m.id}>
              {m.is_unread ? <span className="unread-dot" aria-label="Unread" /> : <span style={{ width: 7 }} />}
              <div className="row-main">
                <div className="email-from">
                  {m.is_flagged && <span title="Flagged" style={{ color: 'var(--accent)' }}>⚑ </span>}
                  {m.from_name}
                </div>
                <div className="row-title" style={{ fontSize: '0.84rem' }}>{m.subject}</div>
                <div className="row-sub mono">{fmtTime(m.received_at, tz)} · {relativeFromNow(m.received_at)}</div>
              </div>
              {m.task_id ? (
                <span className="chip">Task added</span>
              ) : (
                <button
                  className="btn btn-ghost btn-sm"
                  onClick={() =>
                    makeTask.mutate(m.id, {
                      onSuccess: () => toast({ title: 'Task created', body: `Reply: ${m.subject}` }),
                      onError: (err) => toast({ title: 'Could not create task', body: errorMessage(err), tone: 'error' }),
                    })
                  }
                >
                  → Task
                </button>
              )}
            </div>
          ))}
          <Link to="/inbox" className="btn btn-ghost btn-sm" style={{ marginTop: 6 }}>
            Open inbox
          </Link>
        </>
      )}
    </Section>
  );
}
