"""Render the portfolio docs from projects.json.

projects.json is the single source of truth for project names, categories and
progress. This script regenerates:

  - MASTER_PROJECT_TRACKER.md   (whole file)
  - PROJECT_INDEX.md            (whole file)
  - README.md                   (only the block between the PROJECTS markers)
  - PROJECT_NN/README.md        (only while it is still a generated placeholder)

Real project READMEs are never overwritten: once a project starts, its README
loses the placeholder marker and this script leaves it alone.

Usage:
  python shared-resources/scripts/render_docs.py          # write files
  python shared-resources/scripts/render_docs.py --check  # exit 1 if out of date

Stdlib only, so it runs without any project environment.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "projects.json"

PLACEHOLDER_MARK = "<!-- placeholder: generated by render_docs.py -->"
README_START = "<!-- PROJECTS:START (generated by shared-resources/scripts/render_docs.py) -->"
README_END = "<!-- PROJECTS:END -->"

PHASES = ["planning", "frontend", "backend", "database", "testing", "docs", "github"]
BACKEND_PORT_BASE = 8000
FRONTEND_PORT_BASE = 5100


def folder(pid: int) -> str:
    return f"PROJECT_{pid:02d}"


def ports(pid: int) -> tuple[int, int]:
    return BACKEND_PORT_BASE + pid, FRONTEND_PORT_BASE + pid


def load() -> dict:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    projects = data["projects"]
    ids = [p["id"] for p in projects]
    if ids != list(range(1, 51)):
        raise SystemExit(f"projects.json must list ids 1..50 in order, got {ids}")
    for cat in data["categories"]:
        n = sum(1 for p in projects if p["category"] == cat["id"])
        if n != cat["count"]:
            raise SystemExit(f"category {cat['id']} expects {cat['count']} projects, found {n}")
    for key, prog in data.get("progress", {}).items():
        status = prog.get("status", "Pending")
        if status not in data["status_values"]:
            raise SystemExit(f"project {key}: unknown status {status!r}")
        for ph in PHASES:
            if prog.get(ph, "") not in data["phase_values"]:
                raise SystemExit(f"project {key}: bad value for {ph}: {prog.get(ph)!r}")
    return data


def progress(data: dict, pid: int) -> dict:
    prog = {"status": "Pending", "stack": "", "notes": ""}
    prog.update({ph: "" for ph in PHASES})
    prog.update(data.get("progress", {}).get(str(pid), {}))
    return prog


def cell(value: str) -> str:
    return value if value else "—"


def render_tracker(data: dict) -> str:
    counts: dict[str, int] = {s: 0 for s in data["status_values"]}
    for p in data["projects"]:
        counts[progress(data, p["id"])["status"]] += 1
    published = sum(1 for p in data["projects"] if progress(data, p["id"])["github"] == "Done")

    out = [
        "# Master Project Tracker",
        "",
        "Generated from `projects.json` by `shared-resources/scripts/render_docs.py`.",
        "Edit `projects.json`, then re-run the script. Do not edit this table by hand.",
        "",
        "**Summary:** " + " · ".join(f"{s}: {n}" for s, n in counts.items())
        + f" · Published to GitHub: {published}/50",
        "",
        "Phase values: `—` not started · `In progress` · `Done` · `N/A` (not needed) · `Blocked`.",
        "GitHub publication is tracked separately from local completion.",
        "",
    ]
    for cat in data["categories"]:
        out += [f"## {cat['id']}. {cat['name']}", ""]
        out.append("| Project | Name | Planning | Frontend | Backend | Database | Testing | Docs | GitHub | Status |")
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        for p in data["projects"]:
            if p["category"] != cat["id"]:
                continue
            prog = progress(data, p["id"])
            phases = " | ".join(cell(prog[ph]) for ph in PHASES)
            out.append(
                f"| [Project {p['id']:02d}]({folder(p['id'])}/) | {p['name']} | {phases} | **{prog['status']}** |"
            )
        out.append("")
    return "\n".join(out)


def render_index(data: dict) -> str:
    out = [
        "# Project Index",
        "",
        "All 50 projects in their original order, grouped by the seven original categories.",
        "Generated from `projects.json`; descriptions and features come from the source PDF.",
        "",
        "## Contents",
        "",
    ]
    for cat in data["categories"]:
        # GitHub slugs: lowercase, drop punctuation, each space becomes "-" (so " & " -> "--").
        heading = f"{cat['id']}. {cat['name']}".lower()
        anchor = "".join(ch for ch in heading if ch.isalnum() or ch in " -").replace(" ", "-")
        out.append(f"- [{cat['id']}. {cat['name']}](#{anchor}) ({cat['count']} projects)")
    out.append("")
    for cat in data["categories"]:
        out += [f"## {cat['id']}. {cat['name']}", ""]
        for p in data["projects"]:
            if p["category"] != cat["id"]:
                continue
            prog = progress(data, p["id"])
            be, fe = ports(p["id"])
            out += [
                f"### {p['id']:02d}. {p['name']}",
                "",
                f"- **Folder:** [`{folder(p['id'])}/`]({folder(p['id'])}/)",
                f"- **Status:** {prog['status']}",
                f"- **What it does:** {p['what']}",
                f"- **Core features:** {', '.join(p['features'])}",
                f"- **Tech stack:** {prog['stack'] or 'Chosen when the project starts'}",
                f"- **Reserved local ports:** backend `{be}`, frontend `{fe}`",
            ]
            if prog["notes"]:
                out.append(f"- **Notes:** {prog['notes']}")
            out += ["", f"> Original brief: {p['what_original']}", ""]
    return "\n".join(out)


def render_readme_block(data: dict) -> str:
    out = [README_START, ""]
    for cat in data["categories"]:
        out += [f"### {cat['id']}. {cat['name']}", ""]
        out.append("| # | Project | What it does | Stack | Status |")
        out.append("|---|---|---|---|---|")
        for p in data["projects"]:
            if p["category"] != cat["id"]:
                continue
            prog = progress(data, p["id"])
            out.append(
                f"| {p['id']:02d} | [{p['name']}]({folder(p['id'])}/) | {p['what']} "
                f"| {prog['stack'] or '—'} | {prog['status']} |"
            )
        out.append("")
    out.append(README_END)
    return "\n".join(out)


def render_placeholder(data: dict, p: dict) -> str:
    cat = next(c for c in data["categories"] if c["id"] == p["category"])
    be, fe = ports(p["id"])
    features = "\n".join(f"- {f}" for f in p["features"])
    return f"""{PLACEHOLDER_MARK}
# Project {p['id']:02d}: {p['name']}

**Category:** {cat['id']}. {cat['name']}
**Status:** Pending. Not started; work begins only on the explicit command `Start Project {p['id']}`.

## Brief (from the source PDF)

{p['what']}

> Original: {p['what_original']}

### Core features

{features}

## Reserved local ports

| Service | Port |
|---|---|
| Backend / API | {be} |
| Frontend dev server | {fe} |

## Deliverables when the project starts

- [ ] `docs/PRD.md`: problem, users, use cases, MVP and advanced features, user stories
- [ ] `docs/ARCHITECTURE.md`: stack, data model, API, flows
- [ ] Application code (frontend / backend / database as the project needs)
- [ ] Automated tests, run and passing
- [ ] `.env.example` (no real secrets)
- [ ] Real screenshots in `docs/screenshots/`
- [ ] This README replaced with full documentation
"""


def build(data: dict) -> dict[Path, str]:
    files: dict[Path, str] = {
        ROOT / "MASTER_PROJECT_TRACKER.md": render_tracker(data),
        ROOT / "PROJECT_INDEX.md": render_index(data),
    }

    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        raise SystemExit("README.md is missing the PROJECTS markers")
    head, rest = text.split(README_START, 1)
    _, tail = rest.split(README_END, 1)
    files[readme] = head + render_readme_block(data) + tail

    for p in data["projects"]:
        path = ROOT / folder(p["id"]) / "README.md"
        if path.exists() and PLACEHOLDER_MARK not in path.read_text(encoding="utf-8"):
            continue  # real README: hands off
        files[path] = render_placeholder(data, p)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = parser.parse_args()

    files = build(load())
    stale = []
    for path, content in files.items():
        content = content.rstrip("\n") + "\n"
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    if args.check:
        if stale:
            print("Out of date:\n  " + "\n  ".join(stale))
            return 1
        print("All generated docs are up to date.")
        return 0
    print(f"Updated {len(stale)} file(s)." if stale else "Nothing to update.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
